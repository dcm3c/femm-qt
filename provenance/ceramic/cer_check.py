"""cer_check.py -- the numbers and figures behind ceramiccurves.tex.

Ceramic (sintered hard ferrite) entries come in two kinds, and this script
checks both:

  Measured.  Dexter Magnetic Technologies' demagnetization curves at 20 C for
  HF010, HF050, HF070, HF081 and HF083, digitized by the user in
  Magnets/Ceramic/Indox.nb and written as FEMM blocks "Ceramic 1", "Ceramic 5",
  "Ceramic 7", "Ceramic 8A" and "Ceramic 8B" in Magnets/Ceramic/Indox.fem.
  HF050, HF081 and HF083 are smoothed with

      B(H) = (1 - exp(-k (H + Hcb)/Hcb)) (Br + mu0 ur H)           (normal form)

  and HF010 and HF070, whose knees lie in the third quadrant, are straight
  lines from Br to Hcb.

  Typical.  The Chinese Y-grades, for which no credible measured curve is
  held, generated by Magnets/Ceramic/ceramic.nb from the midpoints of the
  Eclipse Magnetics ranges on one shared shape,

      J(H) = (Br - mu0 X Hcj)(1 - exp(-s (H + Hcj)/Hcj)) + mu0 X (H + Hcj),
      X = ur - 1,  B = mu0 H + J,  ur = 1.07,  s = 35        (intrinsic form)

  written to Magnets/Ceramic/Yferrite_typical.fem.

The script also reviews FEMM's stock ceramic entries, and tests how nearly
the two forms are one model: each is fitted to the three smoothed measured
curves, and the intrinsic form, given only Dexter's Br and Hci and the
shared ur and s, is asked to reproduce them.

Usage:  python cer_check.py   -> printed tables, and the paper's figures:
                                 out/ceramiccurves_fig1.png (stock entries),
                                 out/ceramiccurves_fig2.png (measured),
                                 out/ceramiccurves_fig3.png (typical)
"""
