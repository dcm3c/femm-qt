def blocks(path):
    t = open(path, encoding="utf-8", errors="replace").read()
    out = {}
    for m in re.finditer(r"<BeginBlock>(.*?)<EndBlock>", t, re.S):
        b = m.group(1)
        nm = re.search(r'<BlockName>\s*=\s*"([^"]*)"', b).group(1)
        g = lambda k: float(re.search(r"<%s>\s*=\s*([-\d.eE+]+)" % k, b).group(1))
        n = int(g("BHPoints"))
        rows = [l.split() for l in b[b.index("<BHPoints>"):].splitlines()[1:]
                if l.strip()][:n]
        out[nm] = dict(mu=g("Mu_x"), hc=g("H_c"), bh=np.array(rows, float) if n else None)
    return out


def demag(e):
    """Second-quadrant (H <= 0, B) curve of a FEMM magnet block."""
    if e["bh"] is None:
        H = np.linspace(-e["hc"], 0, 400)
        return H, MU0 * e["mu"] * (H + e["hc"])
    return e["bh"][:, 1] - e["hc"], e["bh"][:, 0]


def figures(H, B):
    k = (H <= 0) & (B >= 0)
    H, B = H[k], B[k]
    br = np.interp(0, H, B)
    hcb = -np.interp(0, B, H)
    bhm = (-H * B).max() / 1e3
    top = B >= 0.67 * br
    mur = np.polyfit(H[top], B[top], 1)[0] / MU0
    return br, hcb / 1e3, bhm, mur


def min_slope(H, B, frac=0.5):
    """Smallest segment slope dB/dH, in mu0, above frac*Br."""
    d = np.diff(B) / np.diff(H) / MU0
    k = B[1:] >= frac * B.max()
    return d[k].min()


def normal(H, br, hcb, ur, k):
    return (1 - np.exp(-k * (H + hcb) / hcb)) * (br + MU0 * ur * H)


def intrinsic(H, br, hcj, ur, s):
    X = ur - 1
    return MU0 * H + (br - MU0 * X * hcj) * (1 - np.exp(-s * (H + hcj) / hcj)) \
        + MU0 * X * (H + hcj)


def h_of_b(f, b, lo):
    return brentq(lambda h: f(h) - b, lo, 1.0)


def main():
    # FEMM 4.2's stock entries are optional: without the library (as in the
    # distributed package) section 1 and Figure 1 are skipped
    lib = blocks(LIB) if os.path.exists(LIB) else {}
    meas = blocks(MEAS)
    typ = blocks(TYP)
    # The typical entries are read from TYP only, under their own names.
    # "Y30" is also a stock block in LIB with a different curve; make sure
    # the two never get confused.
    for nm in set(typ) & set(lib):
        assert str(typ[nm]["bh"]) != str(lib[nm]["bh"]), \
            "%s: typical entry identical to FEMM's stock block" % nm

    if lib:
        print("1. FEMM's stock ceramic entries")
        for nm in ("Ceramic 1", "Ceramic 5", "Ceramic 8", "Y25", "Y30"):
            H, B = demag(lib[nm])
            br, hcb, bhm, _ = figures(H, B)
            print("   %-10s %2d points  Br %.3f T  HcB %5.1f kA/m  BHmax %4.1f kJ/m3  "
                  "smallest slope above Br/2 %.2f mu0" % (nm, len(H), br, hcb, bhm, min_slope(H, B)))
        for nm in ("Y25", "Y30"):
            r = ECLIPSE[nm]
            print("   %-10s Eclipse: Br %g-%g mT, HcB %g-%g kA/m, BHmax %g-%g kJ/m3"
                  % (nm, *r[0], *r[1], *r[3]))

    print("\n2. The measured entries (Dexter, 20 C) against Dexter's table and MMPA")
    for nm, dx in ENTRY.items():
        H, B = demag(meas[nm])
        br, hcb, bhm, mur = figures(H, B)
        d = DEXTER[dx]
        m = MMPA[nm]
        form = "table" if meas[nm]["bh"] is not None else "linear"
        print("   %-10s %s %-6s Br %.3f HcB %5.1f BHmax %4.1f recoil %.3f | Dexter %.3f %5.1f %4.1f"
              " | MMPA %-9s %.3f %5.1f %4.1f"
              % (nm, dx, form, br, hcb, bhm, mur, d[1] / 10, d[3] * KOE / 1e3, d[0] * MGOE,
                 m[0], m[1] / 1e3, m[2], m[4]))
        if dx in PTS:
            p = np.array(PTS[dx])
            hp, bp = p[:, 0] * KOE, p[:, 1] / 10
            r = bp - np.interp(hp, H, B)
            print("   %-10s        block vs its %d digitized points: B RMS %.4f T, worst %+.4f T"
                  % ("", len(p), np.sqrt((r ** 2).mean()), r[np.argmax(abs(r))]))

    print("\n3. One model or two: both forms fitted to each measured curve (SI)")
    fitres = {}
    for dx, p in PTS.items():
        p = np.array(p)
        hp, bp = p[:, 0] * KOE, p[:, 1] / 10
        br0, hcb0 = bp[0], -hp[-1]
        pn, _ = curve_fit(normal, hp, bp, p0=[br0, hcb0, 1.07, 30], maxfev=20000)
        pi, _ = curve_fit(intrinsic, hp, bp, p0=[br0, 1.03 * hcb0, 1.07, 50], maxfev=20000)
        rn = bp - normal(hp, *pn)
        ri = bp - intrinsic(hp, *pi)
        fitres[dx] = (pn, pi)
        print("   %s  normal:    Br %.4f  HcB %5.1f kA/m  ur %.3f  k %5.1f   B RMS %.4f T"
              % (dx, pn[0], pn[1] / 1e3, pn[2], pn[3], np.sqrt((rn ** 2).mean())))
        print("   %s  intrinsic: Br %.4f  HcJ %5.1f kA/m  ur %.3f  s %5.1f   B RMS %.4f T"
              "   (Dexter Hci %5.1f kA/m)"
              % (dx, pi[0], pi[1] / 1e3, pi[2], pi[3], np.sqrt((ri ** 2).mean()),
                 DEXTER[dx][2] * KOE / 1e3))
        # the normal form implies an HcJ too: carried past -HcB, J = B - mu0 H
        # reaches zero (first root; the form turns over again further out)
        hs = -pn[1] * np.linspace(1.0001, 3.0, 20000)
        fj = normal(hs, *pn) - MU0 * hs
        i = int(np.argmax(fj < 0))
        hcj_n = -brentq(lambda h: normal(h, *pn) - MU0 * h, hs[i - 1], hs[i])
        print("   %s  HcJ implied by the normal form %5.1f kA/m, by the intrinsic "
              "%5.1f" % (dx, hcj_n / 1e3, pi[1] / 1e3))
        hq = np.linspace(-0.98 * pn[1], 0, 200)
        gap = normal(hq, *pn) - intrinsic(hq, *pi)
        print("   %s  largest gap between the two fitted curves: %.4f T" % (dx, abs(gap).max()))

    print("\n4. The generator (ur %.2f, s %g), given Dexter's Br and Hci, against the "
          "measured curves" % (UR, S))
    for dx, (pn, _) in fitres.items():
        br, hcj = DEXTER[dx][1] / 10, DEXTER[dx][2] * KOE
        f = lambda h: intrinsic(h, br, hcj, UR, S)
        g = lambda h: normal(h, *pn)
        bq = np.linspace(0.01, 0.97 * min(br, pn[0]), 60)
        hm = np.array([h_of_b(f, b, -1.5 * hcj) for b in bq])
        hd = np.array([h_of_b(g, b, -pn[1] - 1) for b in bq])
        d = (hm - hd) / 1e3
        w, k = bq >= 0.2, bq < 0.2
        hcb_m = -h_of_b(f, 0.0, -1.5 * hcj) / 1e3
        print("   %s = %-7s HcB measured %5.1f, generator %5.1f kA/m; H error at fixed B: "
              "above 0.2 T within %.1f kA/m, below 0.2 T within %.1f kA/m"
              % (dx, YMAP[dx], pn[1] / 1e3, hcb_m, abs(d[w]).max(), abs(d[k]).max()))
        # the sign matters for a demagnetization study: d < 0 puts the
        # generator's knee at a larger reverse field than the magnet's own,
        # which overstates what the magnet can take (optimistic)
        print("        below 0.2 T: generator knee beyond the measured one by up to "
              "%.1f kA/m, inside it by up to %.1f kA/m"
              % (max(0.0, -d[k].min()), max(0.0, d[k].max())))

    print("\n5. The typical Y-grade entries against the Eclipse ranges")
    nin = 0
    for nm, e in typ.items():
        g = nm.split(" ")[0]
        H, B = demag(e)
        br, hcb, bhm, mur = figures(H, B)
        r = ECLIPSE[g]
        ok = r[1][0] <= hcb <= r[1][1] and r[3][0] <= bhm <= r[3][1]
        nin += ok
        print("   %-18s Br %.3f  HcB %5.1f (%g-%g)  BHmax %5.2f (%g-%g)  smallest slope %.3f mu0  %s"
              % (nm, br, hcb, *r[1], bhm, *r[3], min_slope(H, B, 0.0), "in range" if ok else "OUT"))
    print("   %d of %d inside both ranges" % (nin, len(typ)))

    # ---- figures -------------------------------------------------------
    col = {"Ceramic 1": "#1b9e77", "Ceramic 5": "#d95f02", "Ceramic 7": "#7570b3",
           "Ceramic 8A": "#e7298a", "Ceramic 8B": "#66a61e"}
    fig, ax = plt.subplots(figsize=(8, 5.5))
    for nm, dx in ENTRY.items():
        H, B = demag(meas[nm])
        ax.plot(H / 1e3, B, "-", color=col[nm], lw=2, label="%s (Dexter %s)" % (nm, dx))
        if dx in PTS:
            p = np.array(PTS[dx])
            ax.plot(p[:, 0] * KOE / 1e3, p[:, 1] / 10, "o", color=col[nm], ms=4, mfc="none")
    ax.set_xlabel("H [kA/m]")
    ax.set_ylabel("B [T]")
    ax.set_xlim(-310, 0)
    ax.set_ylim(0, 0.45)
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8, loc="upper left")
    fig.tight_layout()
    fig.savefig("out/ceramiccurves_fig2.png", dpi=110)  # measured

    fig, ax = plt.subplots(1, 2, figsize=(13, 5.2))
    cmap = plt.get_cmap("viridis")
    names = list(typ)
    for i, nm in enumerate(names):
        H, B = demag(typ[nm])
        ax[0].plot(H / 1e3, B, "-", color=cmap(i / (len(names) - 1)), lw=1.4,
                   label=nm.split(" ")[0])
    pair = {"HF050": "#d95f02", "HF081": "#e7298a", "HF083": "#1b9e77"}
    for dx, (pn, _) in fitres.items():
        H, B = demag(typ[YMAP[dx]])        # Yferrite_typical.fem's own name
        ax[1].plot(H / 1e3, B, "-", color=pair[dx], lw=1.8, label="%s (typical)" % YMAP[dx])
        hq = np.linspace(-pn[1], 0, 300)
        ax[1].plot(hq / 1e3, normal(hq, *pn), "--", color=pair[dx], lw=1.8,
                   label="Dexter %s, measured" % dx)
    ax[0].set_title("The 15 typical Y-grade entries", fontsize=10)
    ax[1].set_title("Typical entries against the measured curve of the same grade", fontsize=10)
    for a in ax:
        a.set_xlabel("H [kA/m]")
        a.set_ylabel("B [T]")
        a.set_xlim(-310, 0)
        a.set_ylim(0, 0.47)
        a.grid(alpha=0.3)
    ax[0].legend(fontsize=7, loc="upper left", ncol=3)
    ax[1].legend(fontsize=8, loc="upper left")
    fig.tight_layout()
    fig.savefig("out/ceramiccurves_fig3.png", dpi=110)  # typical

    if lib:
        fig, ax = plt.subplots(1, 2, figsize=(12, 4.8))
        for nm, c in [("Ceramic 1", "#1b9e77"), ("Ceramic 5", "#d95f02"), ("Ceramic 8", "#e7298a"),
                      ("Y25", "k"), ("Y30", "#7570b3")]:
            H, B = demag(lib[nm])
            ax[0].plot(H / 1e3, B, "o-", color=c, ms=3, lw=1.2, label=nm)
            d = np.diff(B) / np.diff(H) / MU0
            bm = (B[1:] + B[:-1]) / 2
            ax[1].plot(bm, d, "o-", color=c, ms=3, lw=1.2, label=nm)
        ax[1].axhline(1.0, color="gray", lw=0.8, ls=":")
        ax[1].axhspan(1.05, 1.2, color="gray", alpha=0.15, label="MMPA recoil 1.05-1.2")
        ax[0].set_xlabel("H [kA/m]")
        ax[0].set_ylabel("B [T]")
        ax[1].set_xlabel("B [T] (segment midpoint)")
        ax[1].set_ylabel("segment slope dB/dH / mu0")
        ax[1].set_ylim(0.6, 2.0)
        ax[1].set_xlim(0.15, 0.42)
        for a in ax:
            a.grid(alpha=0.3)
            a.legend(fontsize=8, loc="upper left")
        fig.tight_layout()
        fig.savefig("out/ceramiccurves_fig1.png", dpi=110)  # stock
    print("\nwrote %sout/ceramiccurves_fig2.png, fig3.png"
          % ("out/ceramiccurves_fig1.png, " if lib else ""))


if __name__ == "__main__":
    main()
